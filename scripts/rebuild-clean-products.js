async function main() {
  console.log("Starting clean product database rebuild in Supabase...");
  console.log(`Targeting ${cleanProducts.length} authoritative products across Cellphones & Laptops.`);

  for (const prod of cleanProducts) {
    const { id, ...data } = prod;
    const { data: updated, error } = await supabase
      .from("products")
      .upsert({ id, ...data }, { onConflict: "id" })
      .select();

    if (error) {
      console.error(`❌ Failed to upsert product #${id} (${prod.title}):`, error.message);
    } else {
      console.log(`✅ Upserted #${id}: ${prod.title} [Category: ${prod.category}] [Price: $${prod.price}]`);
    }
  }

  // Verify counts
  const { data: all, error: countErr } = await supabase
    .from("products")
    .select("id, title, category, price, is_best_seller, is_new, is_popular, is_deal");

  if (countErr) {
    console.error("Count error:", countErr);
    return;
  }

  const cellphones = all.filter(p => p.category === "cellphones-tablets");
  const laptops = all.filter(p => p.category === "laptops-computers");
  console.log("\n==========================================");
  console.log(`🎉 DATABASE REBUILD SUCCESSFUL!`);
  console.log(`Total Products in Supabase: ${all.length}`);
  console.log(`  • Cellphones & Tablets: ${cellphones.length}`);
  console.log(`  • Laptops & Computers:  ${laptops.length}`);
  console.log(`  • Best Sellers:        ${all.filter(p => p.is_best_seller).length}`);
  console.log(`  • Deals of the Day:    ${all.filter(p => p.is_deal).length}`);
  console.log(`  • New In:              ${all.filter(p => p.is_new).length}`);
  console.log(`  • Popular:             ${all.filter(p => p.is_popular).length}`);
  console.log("==========================================");
}

